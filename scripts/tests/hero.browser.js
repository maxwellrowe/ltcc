(async () => {
  const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
  await wait(200);
  const results = [];
  const check = (name, ok) => results.push({ name, ok });
  const hero = document.querySelector('.ltcc-hero');
  const slider = hero.querySelector('.ltcc-hero-swiper');
  const swiper = slider.swiper;
  const reduced = matchMedia('(prefers-reduced-motion: reduce)').matches;
  check('slider initialized', !!swiper);
  check('autoplay on load unless reduced motion', swiper.autoplay.running === !reduced);
  check('controls shown', !slider.querySelector('.ltcc-hero__controls').hidden);
  const before = swiper.activeIndex;
  await wait(5500);
  check('automatic advancement / reduced-motion pause', reduced ? swiper.activeIndex === before : swiper.activeIndex !== before);
  const pause = slider.querySelector('[data-hero-pause]');
  if (reduced) pause.click();
  pause.click();
  check('pause stops autoplay', !swiper.autoplay.running && pause.getAttribute('aria-label') === 'Play slideshow');
  const index = swiper.activeIndex;
  slider.querySelector('[data-hero-next]').click(); await wait(700);
  check('next works while paused', swiper.activeIndex !== index);
  slider.querySelector('[data-hero-prev]').click(); await wait(700);
  check('previous works', swiper.activeIndex === index);
  pause.click();
  check('play resumes', swiper.autoplay.running && pause.getAttribute('aria-label') === 'Pause slideshow');
  LTCC.components.init(); LTCC.components.init();
  check('repeat init safe', slider.swiper === swiper && slider.querySelectorAll('[data-hero-pause]').length === 1);
  check('single image has no controls', document.querySelectorAll('.ltcc-hero')[1].querySelectorAll('button').length === 0);
  const media = hero.querySelector('.ltcc-hero__media').getBoundingClientRect();
  const copy = hero.querySelector('.ltcc-hero__copy').getBoundingClientRect();
  check('responsive image placement', innerWidth >= 992 ? media.left >= copy.right - 1 : media.bottom <= copy.top + 1);
  check('no overflow', document.documentElement.scrollWidth <= innerWidth);
  const mountain = hero.querySelector('.ltcc-hero__ctas img');
  check('mountain asset geometry', mountain.complete && mountain.naturalWidth > 0 && mountain.width === 48 && mountain.height === 20);
  check('hero image loaded', hero.querySelector('.ltcc-hero__image').naturalWidth > 0);
  document.body.dataset.heroTests = JSON.stringify(results);
})();

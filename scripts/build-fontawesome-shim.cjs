// Generate compatibility CSS from the installed, licensed Font Awesome metadata.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const directory = path.join(root, '_resources/fonts/font-awesome');
const icons = JSON.parse(fs.readFileSync(path.join(directory, 'metadata/icons.json')));
const families = JSON.parse(fs.readFileSync(path.join(directory, 'metadata/icon-families.json')));
for (const [name, icon] of Object.entries(families)) {
  if (!icons[name]) icons[name] = { ...icon, styles: (icon.familyStylesByLicense?.pro || []).map(entry => entry.style) };
}
const shims = JSON.parse(fs.readFileSync(path.join(directory, 'metadata/shims.json')));
const rules = new Map();
const brandCodes = new Set();
const regularCodes = new Set();
function rule(name, target, style) {
  const icon = icons[target];
  if (!icon) throw new Error(`Missing icon: ${target}`);
  const brand = style === 'fab' || icon.styles.includes('brands');
  const regular = style === 'far';
  rules.set(name, `.fa.fa-${name}{--fa:"\\${icon.unicode}";--fa-family:"Font Awesome 7 ${brand ? 'Brands' : 'Sharp'}";--fa-style:${brand || regular ? 400 : 900};font-family:var(--fa-family);font-weight:var(--fa-style)}`);
}
for (const [name, icon] of Object.entries(icons)) {
  if (!icon.styles.includes('brands')) continue;
  rule(name, name, 'fab');
  brandCodes.add(parseInt(icon.unicode, 16));
  for (const alias of icon.aliases?.names || []) rule(alias, name, 'fab');
}
for (const [old, style, target] of shims) {
  if (typeof old === 'string') rule(old, target || old, style);
  else if (style === 'fab') brandCodes.add(old);
  else if (style === 'far') regularCodes.add(old);
}
function face(file, codes) {
  return `@font-face{font-family:"FontAwesome";font-style:normal;font-weight:normal;font-display:block;src:url("../fonts/font-awesome/webfonts/${file}.woff2") format("woff2")${codes ? ';unicode-range:'+ [...codes].map(c=>'U+'+c.toString(16)).join(',') : ''}}`;
}
const css = [
  '/* Generated by scripts/build-fontawesome-shim.cjs. Load after Font Awesome all.min.css. */',
  '.fa{--fa-family:"Font Awesome 7 Sharp";--fa-style:900}',
  ...rules.values(),
  // Support old CSS using font-family: FontAwesome and legacy Unicode codepoints.
  face('fa-sharp-solid-900'), face('fa-sharp-regular-400', regularCodes), face('fa-brands-400', brandCodes),
].join('\n')+'\n';
fs.writeFileSync(path.join(root, '_resources/css/fontawesome-v4-shim.css'), css);
console.log(`Generated ${rules.size} legacy icon mappings.`);
